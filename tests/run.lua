local H = dofile("tests/helpers.lua")
local ranger = H.temp .. "/fake ranger ' ; $(false) ü"
H.write(ranger, vim.fn.readfile(H.root .. "/tests/fixtures/ranger.py"))
assert(vim.uv.fs_chmod(ranger, 448))
local capture = H.temp .. "/capture.json"
local folder = H.temp .. "/folder % # ' | $() ü"
vim.fn.mkdir(folder, "p")
local one = H.write(folder .. "/one % # ' | $() ü.txt")
local two = H.write(folder .. "/two.txt")
local tests = {}
local function test(name, callback)
  tests[#tests + 1] = { name, callback }
end

local function setup(opts)
  opts = vim.tbl_deep_extend("force", { ranger_cmd = ranger }, opts or {})
  H.plugin.setup(opts)
  vim.env.NEORANGER_TEST_CAPTURE = capture
  vim.env.NEORANGER_TEST_FILES = vim.json.encode({ one, two })
  vim.env.NEORANGER_TEST_DIRECTORY = folder
  return opts
end

local function open(directory)
  vim.uv.fs_unlink(capture)
  H.plugin.open(directory)
  local handle = H.handle()
  H.wait(function() return H.contains(handle.buf, "NEORANGER_READY") end, "fake Ranger ready")
  handle.capture = vim.json.decode(table.concat(vim.fn.readfile(capture), "\n"))
  return handle
end

local function cleanup(handle)
  H.closed(handle)
  H.wait(function()
    return vim.fn.isdirectory(vim.fs.dirname(handle.capture.files_result)) == 0
  end, "temporary files removed")
  for _, item in ipairs(vim.api.nvim_get_autocmds({ event = "VimResized" })) do
    assert(not (item.group_name or ""):match("^neoranger_session_"), "session autocmd leaked")
  end
end

test("default, custom, disabled, repeated setup and changed leader mappings", function()
  setup()
  assert(type(vim.fn.maparg(" r", "n", false, true).callback) == "function")
  setup()
  assert(not H.message("already exists"))
  setup({ keymap = "<leader>e" })
  H.eq(vim.fn.maparg(" r", "n"), "")
  assert(type(vim.fn.maparg(" e", "n", false, true).callback) == "function")
  vim.g.mapleader = ","
  setup()
  H.eq(vim.fn.maparg(" e", "n"), "")
  assert(type(vim.fn.maparg(",r", "n", false, true).callback) == "function")
  setup({ keymap = false })
  H.eq(vim.fn.maparg(",r", "n"), "")
  vim.g.mapleader = " "
end)

test("user mappings survive setup and later reconfiguration", function()
  setup({ keymap = false })
  vim.keymap.set("n", " r", "<Nop>")
  setup()
  H.eq(vim.fn.maparg(" r", "n"), "<Nop>")
  assert(H.message("already exists"))
  vim.keymap.del("n", " r")
  setup()
  vim.keymap.set("n", " r", "<Nop>")
  setup({ keymap = false })
  H.eq(vim.fn.maparg(" r", "n"), "<Nop>")
  vim.keymap.del("n", " r")
end)

test("invalid options fail before changing mappings", function()
  setup()
  for _, opts in ipairs({ { window = { width = 0 } }, { cwd_keymap = "bad key" }, { cwd_keymap = "<leader>c" }, { ranger_cmd = {} }, { unknown = true } }) do
    local ok = pcall(H.plugin.setup, opts)
    assert(not ok, "invalid configuration accepted")
  end
  assert(type(vim.fn.maparg(" r", "n", false, true).callback) == "function")
end)

test("buffer-local mapping cannot leave a stale plugin mapping after reconfiguration", function()
  setup()
  vim.keymap.set("n", " r", "<Nop>", { buffer = true })
  setup({ keymap = false })
  H.eq(vim.fn.maparg(" r", "n"), "<Nop>")
  vim.keymap.del("n", " r", { buffer = true })
  H.eq(vim.fn.maparg(" r", "n"), "")
end)

test("current file selected and paths travel unchanged through argv", function()
  setup()
