test("repeated activation reuses one job and resize clamps geometry", function()
  setup()
  local origin = vim.api.nvim_get_current_win()
  local h = open()
  vim.api.nvim_set_current_win(origin)
  H.plugin.open()
  H.eq(vim.api.nvim_get_current_win(), h.win)
  H.eq(vim.b[h.buf].terminal_job_id, h.job)
  H.eq(#vim.api.nvim_list_wins(), 2)
  vim.o.columns = 60
  vim.o.lines = 20
  vim.api.nvim_exec_autocmds("VimResized", {})
  local shape = vim.api.nvim_win_get_config(h.win)
  H.eq(shape.width, 48)
  H.eq(shape.height, 15)
  H.send(h, "quit\n")
  cleanup(h)
end)

