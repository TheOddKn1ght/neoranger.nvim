test("multiple files create ordered tabs and preserve unsaved source", function()
  setup()
  local origin = vim.api.nvim_get_current_buf()
  vim.api.nvim_buf_set_lines(origin, 0, -1, false, { "unsaved work" })
  local cwd = vim.fn.getcwd(-1, -1)
  local h = open()
  H.send(h, "files\n")
  cleanup(h)
  local tabs = vim.api.nvim_list_tabpages()
  H.eq(#tabs, 3)
  H.eq(vim.api.nvim_get_current_tabpage(), tabs[2])
  H.eq(vim.api.nvim_buf_get_name(0), one)
  H.eq(vim.api.nvim_buf_get_name(vim.api.nvim_win_get_buf(vim.api.nvim_tabpage_get_win(tabs[3]))), two)
  H.eq(vim.api.nvim_buf_get_lines(origin, 0, -1, false), { "unsaved work" })
  assert(vim.bo[origin].modified)
  H.eq(vim.fn.getcwd(-1, -1), cwd)
end)

test("directory confirmation applies cd and preserves buffers and tabs", function()
  setup()
  local origin = vim.api.nvim_get_current_win()
  vim.api.nvim_buf_set_lines(0, 0, -1, false, { "keep me" })
  local h = open()
  H.send(h, "cwd\n")
  cleanup(h)
  H.eq(vim.fn.getcwd(-1, -1), vim.uv.fs_realpath(folder))
  H.eq(vim.api.nvim_get_current_win(), origin)
  H.eq(#vim.api.nvim_list_tabpages(), 1)
  H.eq(vim.api.nvim_buf_get_lines(0, 0, -1, false), { "keep me" })
  assert(vim.bo.modified)
  assert(H.message("Working directory:"))
end)

test("directory confirmation refuses active file operations", function()
  setup()
  local cwd = vim.fn.getcwd(-1, -1)
  local h = open()
  H.send(h, "busy\ncwd\n")
  H.wait(function() return H.contains(h.buf, "wait for file operations") end, "active work guard")
  assert(not vim.uv.fs_stat(h.capture.directory_result))
  H.eq(vim.fn.getcwd(-1, -1), cwd)
  H.send(h, "idle\ncwd\n")
  cleanup(h)
  H.eq(vim.fn.getcwd(-1, -1), vim.uv.fs_realpath(folder))
end)

